"""Generate machine-specific FreeCAD macros, plugin files and Codex configuration."""

import argparse
import json
import sys
from pathlib import Path

from . import __version__
from .client import find_freecad_cmd


def generate(workspace, output, freecad_cmd=None, extension_dirs=None):
    workspace = Path(workspace).expanduser().resolve()
    output = Path(output).expanduser().resolve()
    workspace.mkdir(parents=True, exist_ok=True)
    output.mkdir(parents=True, exist_ok=True)
    source = Path(__file__).resolve().parents[1]
    extension_dirs = [str(Path(p).expanduser().resolve()) for p in (extension_dirs or [])]
    extension_config = (
        "from codex_freecad.extension_runtime import get_registry\n"
        f"get_registry({extension_dirs!r})\n"
    )
    state_file = workspace / ".codex-freecad-live.json"
    macro = (
        "# Generated by codex-freecad-setup; run inside FreeCAD.\n"
        "import sys\n"
        f"sys.path.insert(0, {str(source)!r})\n"
        "from codex_freecad import bridge\n"
        "bridge.stop()\n"
        "from codex_freecad import panel\n"
        "panel.shutdown()\n"
        "from codex_freecad.extension_runtime import close_registry\n"
        "close_registry()\n"
        "import importlib\n"
        "importlib.invalidate_caches()\n"
        "for _module_name in ('codex_freecad', 'codex_freecad.engine', 'codex_freecad.extension_schema', 'codex_freecad.extension_runtime', 'codex_freecad.sketches', 'codex_freecad.patterns', 'codex_freecad.parameters', 'codex_freecad.features', 'codex_freecad.assemblies', 'codex_freecad.motion', 'codex_freecad.interference', 'codex_freecad.viewport', 'codex_freecad.client', 'codex_freecad.bridge', 'codex_freecad.panel'):\n"
        "    importlib.reload(importlib.import_module(_module_name))\n"
        "from codex_freecad import bridge\n"
        f"bridge.start({str(workspace)!r}, {str(state_file)!r}, extension_dirs={extension_dirs!r})\n"
        "from codex_freecad import panel\n"
        f"panel.install_command({str(workspace)!r})\n"
        f"panel.show({str(workspace)!r})\n"
    )
    (output / "StartBridge.FCMacro").write_text(macro, encoding="utf-8")
    (output / "OpenFreeCADPanel.FCMacro").write_text(
        "import sys\n"
        + f"sys.path.insert(0, {str(source)!r})\n"
        + extension_config
        + "from codex_freecad import panel\n"
        f"panel.install_command({str(workspace)!r})\n"
        f"panel.show({str(workspace)!r})\n",
        encoding="utf-8",
    )
    workbench = output / "FreeCADMod" / "CodexFreeCAD"
    workbench.mkdir(parents=True, exist_ok=True)
    (workbench / "InitGui.py").write_text(
        "import sys\nimport FreeCADGui as Gui\n"
        + f"sys.path.insert(0, {str(source)!r})\n"
        + extension_config
        + "class CodexCADWorkbench(Gui.Workbench):\n"
        "    MenuText = 'Codex CAD'\n"
        "    ToolTip = 'Codex CAD modeling and assembly tools'\n"
        "    def Initialize(self):\n"
        "        from codex_freecad import panel\n"
        f"        panel.install_command({str(workspace)!r})\n"
        "        self.appendToolbar('Codex CAD', ['CodexFreeCAD_OpenPanel'])\n"
        "        self.appendMenu('Codex CAD', ['CodexFreeCAD_OpenPanel'])\n"
        "    def Activated(self):\n"
        "        from codex_freecad import panel\n"
        f"        panel.show({str(workspace)!r})\n"
        "    def GetClassName(self):\n"
        "        return 'Gui::PythonWorkbench'\n"
        "Gui.addWorkbench(CodexCADWorkbench())\n",
        encoding="utf-8",
    )
    (output / "StopBridge.FCMacro").write_text(
        "import sys\n" + f"sys.path.insert(0, {str(source)!r})\n"
        "from codex_freecad import bridge\nbridge.stop()\n",
        encoding="utf-8",
    )
    (output / "ReloadExtensions.FCMacro").write_text(
        "import sys, json\nimport FreeCAD as App\n"
        + f"sys.path.insert(0, {str(source)!r})\n"
        + "from codex_freecad.engine import Engine\n"
        + f"_reload_result = Engine({str(workspace)!r}, gui=True).reload_extensions()\n"
        + "App.Console.PrintMessage(json.dumps(_reload_result, indent=2) + '\\n')\n",
        encoding="utf-8",
    )
    servers = {}
    for mode in ("live", "headless"):
        args = ["-m", "codex_freecad.server", "--mode", mode, "--workspace", str(workspace)]
        if mode == "headless" and freecad_cmd:
            args += ["--freecad-cmd", find_freecad_cmd(freecad_cmd)]
        if mode == "headless":
            for directory in extension_dirs:
                args += ["--extensions", directory]
        servers["freecad-" + mode] = {"command": sys.executable, "args": args}
    plugin = output / "plugin"
    (plugin / ".codex-plugin").mkdir(parents=True, exist_ok=True)
    manifest = {
        "name": "freecad-modeling",
        "version": __version__,
        "description": "Inspect and edit local FreeCAD models in a live window or background worker.",
        "mcpServers": "./.mcp.json",
        "interface": {
            "displayName": "FreeCAD Modeling",
            "shortDescription": "Edit live and background FreeCAD models",
        },
    }
    (plugin / ".codex-plugin" / "plugin.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    (plugin / ".mcp.json").write_text(
        json.dumps({"mcpServers": servers}, indent=2) + "\n", encoding="utf-8"
    )
    config = []
    for name, server in servers.items():
        config += [
            f"[mcp_servers.{name}]",
            "command = " + json.dumps(server["command"]),
            "args = " + json.dumps(server["args"]),
            "startup_timeout_sec = 30",
            "tool_timeout_sec = 150",
            "",
        ]
    (output / "codex-mcp.toml").write_text("\n".join(config), encoding="utf-8")
    return {
        "workspace": str(workspace),
        "start_macro": str(output / "StartBridge.FCMacro"),
        "panel_macro": str(output / "OpenFreeCADPanel.FCMacro"),
        "reload_macro": str(output / "ReloadExtensions.FCMacro"),
        "extension_dirs": extension_dirs,
        "freecad_workbench": str(workbench),
        "plugin": str(plugin),
        "codex_config": str(output / "codex-mcp.toml"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=Path("models"))
    parser.add_argument("--output", type=Path, default=Path(".local"))
    parser.add_argument("--freecad-cmd")
    parser.add_argument("--extensions", action="append", type=Path)
    args = parser.parse_args()
    print(
        json.dumps(
            generate(args.workspace, args.output, args.freecad_cmd, args.extensions), indent=2
        )
    )


if __name__ == "__main__":
    main()
