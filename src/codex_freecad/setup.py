"""Generate machine-specific FreeCAD macros, plugin files and Codex configuration."""

import argparse
import json
import sys
from pathlib import Path

from . import __version__
from .client import find_freecad_cmd


def generate(workspace, output, freecad_cmd=None):
    workspace = Path(workspace).expanduser().resolve()
    output = Path(output).expanduser().resolve()
    workspace.mkdir(parents=True, exist_ok=True)
    output.mkdir(parents=True, exist_ok=True)
    source = Path(__file__).resolve().parents[1]
    state_file = workspace / ".codex-freecad-live.json"
    macro = (
        "# Generated by codex-freecad-setup; run inside FreeCAD.\n"
        "import sys\n"
        f"sys.path.insert(0, {str(source)!r})\n"
        "from codex_freecad import bridge\n"
        "bridge.stop()\n"
        "import importlib\n"
        "importlib.invalidate_caches()\n"
        "for _module_name in ('codex_freecad', 'codex_freecad.engine', 'codex_freecad.sketches', 'codex_freecad.patterns', 'codex_freecad.parameters', 'codex_freecad.features', 'codex_freecad.assemblies', 'codex_freecad.client', 'codex_freecad.bridge'):\n"
        "    importlib.reload(importlib.import_module(_module_name))\n"
        "from codex_freecad import bridge\n"
        f"bridge.start({str(workspace)!r}, {str(state_file)!r})\n"
    )
    (output / "StartBridge.FCMacro").write_text(macro, encoding="utf-8")
    (output / "StopBridge.FCMacro").write_text(
        "import sys\n" + f"sys.path.insert(0, {str(source)!r})\n"
        "from codex_freecad import bridge\nbridge.stop()\n",
        encoding="utf-8",
    )
    servers = {}
    for mode in ("live", "headless"):
        args = ["-m", "codex_freecad.server", "--mode", mode, "--workspace", str(workspace)]
        if mode == "headless" and freecad_cmd:
            args += ["--freecad-cmd", find_freecad_cmd(freecad_cmd)]
        servers["freecad-" + mode] = {"command": sys.executable, "args": args}
    plugin = output / "plugin"
    (plugin / ".codex-plugin").mkdir(parents=True, exist_ok=True)
    manifest = {
        "name": "freecad-modeling",
        "version": __version__,
        "description": "Inspect and edit local FreeCAD models in a live window or background worker.",
        "mcpServers": "./.mcp.json",
        "interface": {
            "displayName": "FreeCAD Modeling",
            "shortDescription": "Edit live and background FreeCAD models",
        },
    }
    (plugin / ".codex-plugin" / "plugin.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    (plugin / ".mcp.json").write_text(
        json.dumps({"mcpServers": servers}, indent=2) + "\n", encoding="utf-8"
    )
    config = []
    for name, server in servers.items():
        config += [
            f"[mcp_servers.{name}]",
            "command = " + json.dumps(server["command"]),
            "args = " + json.dumps(server["args"]),
            "startup_timeout_sec = 30",
            "tool_timeout_sec = 150",
            "",
        ]
    (output / "codex-mcp.toml").write_text("\n".join(config), encoding="utf-8")
    return {
        "workspace": str(workspace),
        "start_macro": str(output / "StartBridge.FCMacro"),
        "plugin": str(plugin),
        "codex_config": str(output / "codex-mcp.toml"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=Path("models"))
    parser.add_argument("--output", type=Path, default=Path(".local"))
    parser.add_argument("--freecad-cmd")
    args = parser.parse_args()
    print(json.dumps(generate(args.workspace, args.output, args.freecad_cmd), indent=2))


if __name__ == "__main__":
    main()
